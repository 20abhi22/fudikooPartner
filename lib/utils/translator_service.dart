import 'dart:async';
import 'dart:convert';

import 'package:flutter/services.dart' show rootBundle;
import 'package:shared_preferences/shared_preferences.dart';
import 'package:translator/translator.dart';

/// Translates UI copy and keeps the results on disk.
///
/// [AppText] asks for one phrase at a time, so with a cold cache the app
/// translates lazily — every screen shows English until its own network
/// round-trip lands. To avoid that, [warmUp] translates a whole registry of
/// phrases in one pass (behind a loader) when the language changes. Results
/// are persisted, so the translated copy also survives a restart.
///
/// The registry is exactly `assets/i18n/source_phrases.json`, generated by
/// `dart run tool/extract_translation_phrases.dart`. Learning phrases only as
/// they render is not enough: the app would only ever know the screens you had
/// already opened, so a language switch still left every unvisited page in
/// English until it fetched its own copy — the text visibly changed *after*
/// the page opened.
///
/// Text seen at runtime is deliberately *not* added to the registry. Almost all
/// of it is per-record data — enquiry ids, customer names, free-text menus —
/// and once it is in the registry every future warm-up pays to translate it
/// again. On a screen that lists other people's enquiries that grows without
/// bound, and the language switch gets slower the longer the app is used.
/// Such text still translates on demand through [translate] and is still
/// cached; it is only excluded from the up-front pass.
class TranslatorService {
  static final _translator = GoogleTranslator();

  static const _prefKey = 'selected_language';
  static const _bundledRegistryAsset = 'assets/i18n/source_phrases.json';
  static const _registryPrefKey = 'translation_source_phrases';
  static const _cachePrefixKey = 'translation_cache_';

  /// Phrases packed into a single translate request during warm-up. The
  /// endpoint happily translates a multi-line blob and returns it line for
  /// line, so ~320 phrases cost ~16 round-trips instead of ~320.
  static const int _chunkPhraseCount = 20;

  /// Character ceiling for one chunk. The request carries the text as a query
  /// parameter, so an unbounded blob risks a rejected URL.
  static const int _chunkCharBudget = 900;

  /// Chunks in flight at once. Four requests of twenty phrases finishes the
  /// whole registry in a handful of rounds without hammering the endpoint.
  static const int _chunkConcurrency = 4;

  /// Writes are debounced: a single language switch touches the cache
  /// hundreds of times, and each write re-encodes the whole map.
  static const Duration _persistDelay = Duration(seconds: 2);

  static String _currentLanguage = 'en';
  static final Map<String, String> _cache = {};
  static final Set<String> _sourcePhrases = {};
  static Timer? _persistTimer;

  static String get currentLanguage => _currentLanguage;

  /// Call once at app startup.
  static Future<void> loadSavedLanguage() async {
    final prefs = await SharedPreferences.getInstance();
    _currentLanguage = prefs.getString(_prefKey) ?? 'en';
    _sourcePhrases
      ..clear()
      ..addAll(await _bundledPhrases());
    // Drop the registry earlier builds accumulated at runtime: it is the
    // per-record text described above, and left in place it would keep
    // slowing every warm-up down.
    await prefs.remove(_registryPrefKey);
    await _loadCache(_currentLanguage);
  }

  /// The build-time phrase list shipped with the app.
  static Future<Set<String>> _bundledPhrases() async {
    try {
      final raw = await rootBundle.loadString(_bundledRegistryAsset);
      final decoded = jsonDecode(raw) as List<dynamic>;
      return decoded.map((e) => e.toString()).toSet();
    } catch (_) {
      // Missing or malformed asset: fall back to learning phrases at runtime.
      return <String>{};
    }
  }

  /// Phrases that still need fetching for [langCode]. Zero means a language
  /// switch (or a restart) will render fully translated with no visible swap.
  static int pendingPhraseCount([String? langCode]) {
    final lang = langCode ?? _currentLanguage;
    if (lang == 'en') return 0;
    return _sourcePhrases
        .where((phrase) => !_cache.containsKey(_cacheKey(lang, phrase)))
        .length;
  }

  static Future<void> setLanguage(String langCode) async {
    _currentLanguage = langCode;
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(_prefKey, langCode);
    await _loadCache(langCode);
  }

  /// The already-known translation for [text], or null when it still has to be
  /// fetched. Lets a widget paint the right words on its first frame instead
  /// of showing English and swapping it out a moment later.
  static String? cached(String text) {
    if (_currentLanguage == 'en') return text;
    return _cache[_cacheKey(_currentLanguage, text)];
  }

  static Future<String> translate(String text) async {
    if (_currentLanguage == 'en') return text;

    final key = _cacheKey(_currentLanguage, text);
    final hit = _cache[key];
    if (hit != null) return hit;

    final translated = await _fetch(text, _currentLanguage);
    if (translated == null) return text;

    _cache[key] = translated;
    _schedulePersist();
    return translated;
  }

  /// Translates every phrase the app knows about so a language switch lands on
  /// a fully translated UI rather than translating screen by screen.
  ///
  /// [onProgress] reports 0..1 and is safe to drive a progress indicator with.
  static Future<void> warmUp(
    String langCode, {
    void Function(double progress)? onProgress,
  }) async {
    if (langCode == 'en') {
      onProgress?.call(1);
      return;
    }

    await _loadCache(langCode);

    final pending = _sourcePhrases
        .where((phrase) => !_cache.containsKey(_cacheKey(langCode, phrase)))
        .toList();

    if (pending.isEmpty) {
      onProgress?.call(1);
      await _persist(langCode);
      return;
    }

    final chunks = _buildChunks(pending);
    var done = 0;

    for (var start = 0; start < chunks.length; start += _chunkConcurrency) {
      final round = chunks.skip(start).take(_chunkConcurrency).toList();
      await Future.wait(round.map((chunk) => _translateChunk(chunk, langCode)));

      for (final chunk in round) {
        done += chunk.length;
      }
      onProgress?.call(done / pending.length);
      // Persist as we go: a warm-up interrupted halfway keeps what it fetched
      // instead of paying for those phrases again next time.
      await _persist(langCode);
    }
  }

  /// Groups [phrases] into blobs small enough to translate in one request.
  ///
  /// A phrase that already contains a newline gets a chunk to itself — the
  /// joined blob is split back apart on newlines, so an embedded one would
  /// misalign every phrase after it.
  static List<List<String>> _buildChunks(List<String> phrases) {
    final chunks = <List<String>>[];
    var current = <String>[];
    var currentChars = 0;

    for (final phrase in phrases) {
      if (phrase.contains('\n')) {
        chunks.add([phrase]);
        continue;
      }

      if (current.isNotEmpty &&
          (current.length >= _chunkPhraseCount ||
              currentChars + phrase.length > _chunkCharBudget)) {
        chunks.add(current);
        current = <String>[];
        currentChars = 0;
      }

      current.add(phrase);
      currentChars += phrase.length + 1;
    }

    if (current.isNotEmpty) chunks.add(current);
    return chunks;
  }

  /// Translates one chunk and writes the results into the cache.
  ///
  /// Falls back to one request per phrase when the response does not come back
  /// with the same number of lines it was given — a mismatch means the lines no
  /// longer line up with their sources, and a wrong translation cached against
  /// a phrase would stick around.
  static Future<void> _translateChunk(
    List<String> chunk,
    String langCode,
  ) async {
    if (chunk.length > 1) {
      final blob = await _fetch(chunk.join('\n'), langCode);
      final lines = blob?.split('\n');
      if (lines != null && lines.length == chunk.length) {
        for (var i = 0; i < chunk.length; i++) {
          final translated = lines[i].trim();
          if (translated.isNotEmpty) {
            _cache[_cacheKey(langCode, chunk[i])] = translated;
          }
        }
        return;
      }
    }

    await Future.wait(
      chunk.map((phrase) async {
        final translated = await _fetch(phrase, langCode);
        if (translated != null) {
          _cache[_cacheKey(langCode, phrase)] = translated;
        }
      }),
    );
  }

  static Future<String?> _fetch(String text, String langCode) async {
    try {
      final result = await _translator.translate(text, to: langCode);
      return result.text;
    } catch (_) {
      // Offline or rate-limited: the caller falls back to the source text and
      // the phrase stays in the registry for the next warm-up.
      return null;
    }
  }

  static String _cacheKey(String langCode, String text) => '${langCode}_$text';

  static void _schedulePersist() {
    _persistTimer?.cancel();
    _persistTimer = Timer(_persistDelay, () => _persist(_currentLanguage));
  }

  static Future<void> _persist(String langCode) async {
    _persistTimer?.cancel();
    if (langCode == 'en') return;

    final prefs = await SharedPreferences.getInstance();

    final prefix = '${langCode}_';
    final entries = <String, String>{};
    _cache.forEach((key, value) {
      if (key.startsWith(prefix)) entries[key.substring(prefix.length)] = value;
    });
    await prefs.setString('$_cachePrefixKey$langCode', jsonEncode(entries));
  }

  static Future<void> _loadCache(String langCode) async {
    if (langCode == 'en') return;
    final prefs = await SharedPreferences.getInstance();
    final raw = prefs.getString('$_cachePrefixKey$langCode');
    if (raw == null) return;

    try {
      final decoded = jsonDecode(raw) as Map<String, dynamic>;
      decoded.forEach((phrase, translation) {
        _cache[_cacheKey(langCode, phrase)] = translation.toString();
      });
    } catch (_) {
      // Corrupt cache: fall back to translating on demand.
    }
  }
}
